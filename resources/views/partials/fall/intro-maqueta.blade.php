            <h1 class="intro-main-title" id="intro-title">
                Empire State Building:
                <span>La Caída de King Kong</span>
            </h1>

            <p class="intro-description">
                Inspirada en la escena cumbre de <strong>King Kong (2005)</strong>, esta atracción transforma el
                rascacielos más emblemático de Nueva York en una torre de caída libre vertical. A diferencia de los
                sistemas convencionales, aquí es el propio <strong>King Kong</strong> quien sujeta el carrito con los
                pasajeros y los eleva a lo largo de la fachada de piedra caliza hasta alcanzar la aguja superior.
            </p>

            <p class="intro-description">
                Una vez en la cúspide del edificio, tras quedar suspendidos en el punto más alto del parque, el
                mecanismo libera el carrito provocando un descenso en caída libre hasta la plataforma de frenado en
                la base.
            </p>

